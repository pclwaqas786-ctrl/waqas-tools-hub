"""Book to Skill Lite — a small, honest subset of virgiliojr94/book-to-skill.

Upload a PDF -> pypdf extracts text -> text is split into chapters by heading
heuristics -> a structured Markdown draft is produced with per-chapter excerpts
and key terms from word-frequency analysis.

IMPORTANT: this is a heuristic draft, NOT LLM-quality extraction. Every page
says so. A human must review and rewrite the draft before it becomes a skill.
"""
import re
from collections import Counter

from pypdf import PdfReader

STOPWORDS = {
    "the", "and", "for", "with", "this", "that", "from", "have", "were",
    "will", "would", "there", "their", "what", "which", "when", "your",
    "about", "into", "over", "after", "also", "more", "than", "then",
    "them", "they", "been", "are", "was", "has", "had", "can", "all",
    "each", "other", "some", "such", "only", "its", "our", "out", "who",
    "get", "how", "her", "his", "she", "you", "not", "but", "between",
    "under", "while", "where", "these", "those", "being", "because",
    "should", "could", "does", "doing", "very", "much", "many", "most",
    "such", "like", "just", "well", "even", "back", "within", "without",
}

MAX_CHARS = 400_000  # safety cap on processed text

_HEADING_NUM = re.compile(r"^(chapter|part|section|unit|module)\s+[\divxlc0-9]+.*$",
                          re.IGNORECASE)
_HEADING_DOTTED = re.compile(r"^\d+(\.\d+)*\s+[A-Z].{2,70}$")


def _is_heading(line):
    s = line.strip()
    if not (3 <= len(s) <= 90):
        return False
    if _HEADING_NUM.match(s):
        return True
    if s.isupper() and len(s.split()) <= 10 and not s.endswith("."):
        return True
    if _HEADING_DOTTED.match(s):
        return True
    return False


def extract_pdf_text(file_obj):
    """Returns (full_text, page_count). Raises ValueError on bad PDFs."""
    try:
        reader = PdfReader(file_obj)
    except Exception as e:
        raise ValueError(f"Could not read the PDF: {e}")
    pages = len(reader.pages)
    if pages == 0:
        raise ValueError("The PDF has no pages.")
    parts = []
    for page in reader.pages:
        try:
            parts.append(page.extract_text() or "")
        except Exception:
            parts.append("")
    text = "\n".join(parts)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    if not text:
        raise ValueError("No extractable text found — the PDF may be scanned images.")
    truncated = len(text) > MAX_CHARS
    return text[:MAX_CHARS], pages, truncated


def split_into_chapters(text):
    """Split text into (title, body) chapters using heading heuristics."""
    chapters = []
    current_title, current_lines = None, []
    for line in text.splitlines():
        if _is_heading(line) and (current_title is not None or current_lines):
            if current_title is None:
                current_title = "Introduction"
            chapters.append((current_title, "\n".join(current_lines).strip()))
            current_title, current_lines = line.strip(), []
        else:
            if current_title is None and _is_heading(line):
                current_title = line.strip()
            else:
                current_lines.append(line)
    if current_title is None:
        current_title = "Introduction"
    if current_lines or not chapters:
        chapters.append((current_title, "\n".join(current_lines).strip()))
    chapters = [(t, b) for t, b in chapters if b.strip()]

    if len(chapters) < 2 and text.strip():
        # No usable headings: fall back to equal auto-splits, labelled honestly.
        n = 5
        size = max(1, len(text) // n)
        chapters = []
        for i in range(n):
            chunk = text[i * size:(i + 1) * size].strip()
            if chunk:
                chapters.append(
                    (f"Part {i + 1} (auto-split — no headings found)", chunk))
    return chapters


def key_terms(text, n=15):
    words = re.findall(r"[a-zA-Z]{5,}", text.lower())
    words = [w for w in words if w not in STOPWORDS]
    return Counter(words).most_common(n)


def build_markdown_draft(filename, text, pages, truncated=False):
    """Build the Markdown draft. Clearly labelled as a draft."""
    title = re.sub(r"\.pdf$", "", filename or "document", flags=re.IGNORECASE)
    title = title.replace("_", " ").replace("-", " ").strip() or "document"
    chapters = split_into_chapters(text)
    overall_terms = key_terms(text, 20)

    lines = [
        f"# {title} — Skill Draft",
        "",
        "> **DRAFT — generated by word-frequency heuristics, NOT an LLM.**",
        "> Chapters were split by heading patterns (or auto-split when no",
        "> headings were found). Review, correct and rewrite every section",
        "> before using this as a skill.",
        "",
        f"- Source file: `{filename}`",
        f"- Pages: {pages}",
        f"- Extracted characters: {len(text):,}" + (" (truncated)" if truncated else ""),
        f"- Chapters detected: {len(chapters)}",
        "",
        "## Key terms (whole document)",
        "",
        ", ".join(f"**{w}** ({c})" for w, c in overall_terms) or "_none_",
        "",
    ]
    for i, (ctitle, body) in enumerate(chapters, 1):
        excerpt = body[:600].strip()
        if len(body) > 600:
            excerpt += "..."
        terms = key_terms(body, 8)
        lines += [
            f"## Chapter {i}: {ctitle}",
            "",
            "**Excerpt (first ~600 chars):**",
            "",
            excerpt or "_empty_",
            "",
            "**Key terms:** " + (", ".join(f"{w} ({c})" for w, c in terms) or "_none_"),
            "",
            "**TODO (human review):** rewrite this chapter as a skill section — "
            "learning objectives, key procedures, worked examples.",
            "",
        ]
    lines += [
        "---",
        "_Generated by Waqas Tools Hub · Book to Skill Lite_",
    ]
    return "\n".join(lines), len(chapters)
